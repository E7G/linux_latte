/* Actual installer, with synchronous _REG reentry and allocation/ACPI stubs.
 * No AML interpreter, PMIC access, policy, kernel installation or hardware test.
 */
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <errno.h>

typedef uint16_t u16;
typedef uint32_t u32;
typedef uint64_t u64;
typedef void *acpi_handle;
typedef int acpi_status;
typedef void (*test_handler)(void);
struct mutex { int initialized; };
struct device { int unused; };
struct regmap { int unused; };
struct acpi_lpat_conversion_table { int unused; };
struct intel_pmic_opregion;
#define GFP_KERNEL 0
#define AE_OK 0
#define ACPI_FAILURE(status) ((status) != AE_OK)
#define PMIC_POWER_OPREGION_ID 0x8d
#define PMIC_THERMAL_OPREGION_ID 0x8c
#define PMIC_REGS_OPREGION_ID 0x8f

static unsigned int checks, cases;
#define CHECK(expr) do { checks++; if (!(expr)) { \
	fprintf(stderr, "FAIL line %d: %s\n", __LINE__, #expr); exit(64); \
} } while (0)

static struct device device;
static struct regmap regmap;
static struct acpi_lpat_conversion_table lpat;
static int handle;
static int alloc_fail, fail_at, calls, freed, have_lpat, removed_count;
static int removed[2];
static void *allocated;
static struct intel_pmic_opregion *active_context;

static void mutex_init(struct mutex *lock) { lock->initialized = 1; }
static void *devm_kzalloc(struct device *dev, size_t size, int flags);
static struct acpi_lpat_conversion_table *acpi_lpat_get_conversion_table(acpi_handle h);
static void acpi_lpat_free_conversion_table(struct acpi_lpat_conversion_table *p);
static acpi_status acpi_install_address_space_handler(acpi_handle h, int id,
					 test_handler fn, void *setup, void *ctx);
static void acpi_remove_address_space_handler(acpi_handle h, int id, test_handler fn);
static void intel_pmic_power_handler(void) { }
static void intel_pmic_thermal_handler(void) { }
static void intel_pmic_regs_handler(void) { }

/* Generated by the runner from the actual kernel source, without edits. */
#include "pmic-installer-under-test.h"

static int get_power(struct regmap *map, int reg, int bit, u64 *value)
{
	CHECK(map == &regmap && reg == 17 && bit == 2);
	*value = 1;
	return 0;
}

static int get_temp(struct regmap *map, int reg)
{
	CHECK(map == &regmap && reg == 19);
	return 33000;
}

static struct intel_pmic_opregion_data data = {
	.get_power = get_power,
	.get_raw_temp = get_temp,
};

static void check_reentry(struct intel_pmic_opregion *ctx, int id)
{
	u64 value = 0;

	CHECK(ctx && ctx->lock.initialized && ctx->regmap == &regmap);
	CHECK(ctx->data == &data);
	CHECK(ctx->lpat_table == (have_lpat ? &lpat : NULL));
	/* Invoke the same driver callbacks that a connecting _REG may access. */
	if (id == PMIC_POWER_OPREGION_ID) {
		CHECK(!ctx->data->get_power(ctx->regmap, 17, 2, &value));
		CHECK(value == 1);
	} else if (id == PMIC_THERMAL_OPREGION_ID) {
		CHECK(ctx->data->get_raw_temp(ctx->regmap, 19) == 33000);
	}
}

static void *devm_kzalloc(struct device *dev, size_t size, int flags)
{
	CHECK(dev == &device && flags == GFP_KERNEL && !allocated);
	if (alloc_fail)
		return NULL;
	allocated = calloc(1, size);
	CHECK(allocated);
	return allocated;
}

static struct acpi_lpat_conversion_table *acpi_lpat_get_conversion_table(acpi_handle h)
{
	CHECK(h == &handle);
	return have_lpat ? &lpat : NULL;
}

static void acpi_lpat_free_conversion_table(struct acpi_lpat_conversion_table *p)
{
	CHECK(p == (have_lpat ? &lpat : NULL));
	freed++;
}

static acpi_status acpi_install_address_space_handler(acpi_handle h, int id,
					 test_handler fn, void *setup, void *ctx)
{
	CHECK(h == &handle && !setup);
	CHECK((id == PMIC_POWER_OPREGION_ID && fn == intel_pmic_power_handler) ||
	      (id == PMIC_THERMAL_OPREGION_ID && fn == intel_pmic_thermal_handler) ||
	      (id == PMIC_REGS_OPREGION_ID && fn == intel_pmic_regs_handler));
	calls++;
	if (calls == fail_at)
		return 1;
	active_context = ctx;
	check_reentry(ctx, id);
	return AE_OK;
}

static void acpi_remove_address_space_handler(acpi_handle h, int id, test_handler fn)
{
	CHECK(h == &handle && removed_count < 2);
	CHECK((id == PMIC_POWER_OPREGION_ID && fn == intel_pmic_power_handler) ||
	      (id == PMIC_THERMAL_OPREGION_ID && fn == intel_pmic_thermal_handler));
	check_reentry(active_context, id);
	removed[removed_count++] = id;
}

static void reset(void)
{
	free(allocated);
	allocated = NULL;
	active_context = NULL;
	intel_pmic_opregion = NULL;
	alloc_fail = fail_at = calls = freed = removed_count = 0;
	cases++;
}

int main(void)
{
	int power, thermal, present, fail, total, ret, expected[2], n;

	for (power = 0; power < 2; power++) {
		for (thermal = 0; thermal < 2; thermal++) {
			for (present = 0; present < 2; present++) {
				total = power + thermal + 1;
				for (fail = 0; fail <= total; fail++) {
					reset();
					data.power_table_count = power;
					data.thermal_table_count = thermal;
					have_lpat = present;
					fail_at = fail;
					ret = intel_pmic_install_opregion_handler(&device, &handle, &regmap, &data);
					CHECK(calls == (fail ? fail : total));
					if (!fail) {
						CHECK(!ret && !freed && !removed_count);
						CHECK(intel_pmic_opregion == allocated);
						check_reentry(intel_pmic_opregion, PMIC_REGS_OPREGION_ID);
					} else {
						CHECK(ret == -ENODEV && freed == 1 && !intel_pmic_opregion);
						n = 0;
						if (fail == total && thermal)
							expected[n++] = PMIC_THERMAL_OPREGION_ID;
						if (fail > 1 && power)
							expected[n++] = PMIC_POWER_OPREGION_ID;
						CHECK(removed_count == n);
						while (n--)
							CHECK(removed[n] == expected[n]);
					}
				}
			}
		}
	}
	reset();
	CHECK(intel_pmic_install_opregion_handler(NULL, &handle, &regmap, &data) == -EINVAL);
	CHECK(intel_pmic_install_opregion_handler(&device, &handle, NULL, &data) == -EINVAL);
	CHECK(intel_pmic_install_opregion_handler(&device, &handle, &regmap, NULL) == -EINVAL);
	CHECK(intel_pmic_install_opregion_handler(&device, NULL, &regmap, &data) == -ENODEV);
	CHECK(!allocated && !calls && !freed);
	reset();
	alloc_fail = 1;
	CHECK(intel_pmic_install_opregion_handler(&device, &handle, &regmap, &data) == -ENOMEM);
	CHECK(!allocated && !calls && !freed);
	free(allocated);
	printf("PASS %u cases, %u checks; actual installer, synchronous fake _REG only\n", cases, checks);
	return 0;
}
